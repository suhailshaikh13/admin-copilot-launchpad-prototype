export function getCannedResponse(message: string, businessName = 'your business'): string | undefined {
  const trimmed = message.trim()
  if (trimmed === 'Go live quickly' || trimmed.toLowerCase().includes('go live')) {
    return getGoLiveQuicklyResponse(businessName)
  }

  if (trimmed === 'Bring in your team' || trimmed.toLowerCase() === 'bring in your team') {
    return getBringInTeamResponse(businessName)
  }

  if (trimmed === 'Try a sample ticket' || trimmed.toLowerCase() === 'try a sample ticket') {
    return getTrySampleTicketResponse(businessName)
  }

  if (trimmed === 'Preview Help center' || trimmed.toLowerCase() === 'preview help center') {
    return getPreviewHelpCenterResponse(businessName)
  }

  if (CANNED_RESPONSES[trimmed] && CANNED_RESPONSES[trimmed] !== 'GO_LIVE_TEMPLATE') {
    return CANNED_RESPONSES[trimmed]
  }

  const lower = trimmed.toLowerCase()
  for (const [key, value] of Object.entries(CANNED_RESPONSES)) {
    if (key === 'Go live quickly' || value === 'GO_LIVE_TEMPLATE') continue
    if (key.toLowerCase() === lower) return value
  }

  return undefined
}

export function isGoLiveQuery(message: string): boolean {
  return message.trim().toLowerCase().includes('go live')
}

export function parseSuggestions(text: string): { content: string; suggestions: string[] } {
  const match = text.match(/<suggestions>([\s\S]*?)<\/suggestions>\s*$/)
  if (!match) return { content: text, suggestions: [] }
  const content = text.slice(0, match.index).trimEnd()
  const chips = [...match[1].matchAll(/<chip>(.*?)<\/chip>/g)]
    .map(m => m[1].trim()).filter(Boolean).slice(0, 5)
  return { content, suggestions: chips }
}

export type AssistantWidget = 'team-invite' | 'sample-ticket' | 'help-center-preview'

export function parseAssistantPayload(text: string): {
  content: string
  suggestions: string[]
  widget?: AssistantWidget
} {
  const { content: withWidget, suggestions } = parseSuggestions(text)
  const widgetMatch = withWidget.match(/<widget>([\s\S]*?)<\/widget>\s*/)
  if (!widgetMatch) {
    return { content: withWidget, suggestions }
  }
  const widgetId = widgetMatch[1].trim()
  const content = withWidget.replace(widgetMatch[0], '').trimEnd()
  const widget: AssistantWidget | undefined =
    widgetId === 'team-invite'
      ? 'team-invite'
      : widgetId === 'sample-ticket'
        ? 'sample-ticket'
        : widgetId === 'help-center-preview'
          ? 'help-center-preview'
          : undefined
  return { content, suggestions, widget }
}

export async function streamChat(
  messages: ChatMessage[],
  onChunk: (text: string) => void,
  onDone: () => void,
  onError: (error: Error) => void,
  signal?: AbortSignal
): Promise<void> {
  try {
    const response = await fetch('/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        anthropic_version: 'bedrock-2023-05-31',
        max_tokens: 4096,
        system: SYSTEM_PROMPT,
        messages: messages.map(({ role, content }) => ({ role, content })),
      }),
      signal,
    })

    if (!response.ok) {
      const body = await response.text()
      throw new Error(`API error: ${response.status} ${body}`)
    }

    const reader = response.body?.getReader()
    if (!reader) throw new Error('Response body is not readable')

    let buffer: Uint8Array<ArrayBufferLike> = new Uint8Array(0)

    while (true) {
      const { done, value } = await reader.read()
      if (done) break

      buffer = concatBuffers(buffer, value)
      const { events, remaining } = parseAllMessages(buffer)
      buffer = remaining

      for (const event of events) {
        if (event.type === 'content_block_delta' && event.delta?.type === 'text_delta' && event.delta.text) {
          onChunk(event.delta.text)
        }
        if (event.type === 'message_stop') {
          onDone()
          return
        }
        if (event.type === 'error') {
          throw new Error(`Stream error: ${JSON.stringify(event.message)}`)
        }
      }
    }

    onDone()
  } catch (error) {
    if (signal?.aborted) return
    onError(error instanceof Error ? error : new Error(String(error)))
  }
}
